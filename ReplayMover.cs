using System;
using UnityEngine;

namespace DefaultNamespace
{
	[RequireComponent(typeof(PositionSaver))]
	public class ReplayMover : MonoBehaviour
	{
		private PositionSaver _save;

		private int _index;
		private PositionSaver.Data _prev;
		private float _duration;

		private void Start()
		{
            ////todo comment: зачем нужны эти проверки? 
            ///!TryGetComponent(out _save): Эта проверка пытается найти компонент PositionSaver на том же игровом объекте.
			///Использование TryGetComponent вместо GetComponent является более безопасной практикой, так как оно не вызовет ошибку, если компонент не найден, а просто вернёт false. 
			///Если компонент отсутствует, скрипт не сможет работать.
			///_save.Records.Count == 0: Эта проверка гарантирует, что в компоненте PositionSaver есть данные для воспроизведения.
			///Если список Records пуст, то двигаться объекту некуда, и выполнение скрипта не имеет смысла.
            if (!TryGetComponent(out _save) || _save.Records.Count == 0)
			{
				Debug.LogError("Records incorrect value", this);
                //todo comment: Для чего выключается этот компонент?
                //Предотвратить возможные ошибки, например, IndexOutOfRangeException,
                //которые возникли бы при попытке доступа к несуществующим элементам в пустом списке Records.
                //Оптимизировать производительность, так как неактивный скрипт не тратит ресурсы процессора на обновление каждый кадр.
                enabled = false;
			}
		}

		private void Update()
		{
			var curr = _save.Records[_index];
            //todo comment: Что проверяет это условие (с какой целью)? 
            //Time.time — это текущее игровое время (в секундах с начала игры).
            //curr.Time — это время, когда объект должен был находиться в точке, на которую сейчас указывает индекс _index.
            //Цель этого условия — проверить, наступил ли в игре момент, когда нужно перейти к следующей ключевой точке.
            //Если текущее время стало больше времени следующей точки, значит, объект уже должен быть там (или даже дальше).
            //В этот момент скрипт:
            //Сохраняет текущую точку как предыдущую (_prev = curr;).
            //Увеличивает индекс (_index++), чтобы на следующем кадре использовать уже следующую точку из списка в качестве целевой.

            if (Time.time > curr.Time)
			{
				_prev = curr;
				_index++;
                //todo comment: Для чего нужна эта проверка?
                //Эта проверка служит для определения конца траектории.
                //Когда индекс _index становится равным количеству записей в списке,
                //это означает, что скрипт достиг последней точки и больше точек для воспроизведения нет.
                //остановить движение и не пытаться получить доступ к элементу за пределами массива (что вызвало бы ошибку), скрипт:
                //Выключает себя(enabled = false).
                //Логирует сообщение о завершении воспроизведения.
                if (_index >= _save.Records.Count)
				{
					enabled = false;
					Debug.Log($"<b>{name}</b> finished", this);
				}
			}
            //todo comment: Для чего производятся эти вычисления (как в дальнейшем они применяются)?
            //Это вычисление определяет коэффициент интерполяции (t) для функции Vector3.Lerp.
            //Формула (Time.time - _prev.Time) / (curr.Time - _prev.Time) вычисляет,
            //какую долю времени между двумя ключевыми кадрами (_prev и curr) уже прошло с момента Time.time.
            //Результат (delta) будет находиться в диапазоне от 0 (когда Time.time равно _prev.Time) до 1 (когда Time.time равно curr.Time).
            //Этот коэффициент показывает, насколько далеко объект должен продвинуться от позиции _prev к позиции curr.
            //В дальнейшем этот коэффициент delta передаётся в функцию Vector3.Lerp, которая и вычисляет итоговую позицию объекта.
            var delta = (Time.time - _prev.Time) / (curr.Time - _prev.Time);
            //todo comment: Зачем нужна эта проверка?
            //Эта проверка — защита от деления на ноль.
            //Если две последовательные точки в списке Records были записаны в один и тот же момент времени (то есть curr.Time == _prev.Time),
            //то знаменатель в формуле (curr.Time - _prev.Time) станет равен нулю.
            //В программировании деление на ноль для чисел с плавающей запятой (float) даёт результат NaN (Not a Number).
            //Если передать NaN в функцию Vector3.Lerp, её поведение станет непредсказуемым.
            //Эта проверка обнаруживает такую ситуацию и принудительно устанавливает delta в 0,
            //что корректно "привязывает" объект к позиции _prev до тех пор, пока не наступит время следующей уникальной точки.
            if (float.IsNaN(delta)) delta = 0f;
            //todo comment: Опишите, что происходит в этой строчке так подробно, насколько это возможно
            //Эта строка является финальным шагом вычисления новой позиции объекта на каждом кадре. Вот что происходит по шагам:
            //Вызов функции: Вызывается статический метод Vector3.Lerp, который предназначен для линейной интерполяции между двумя трёхмерными векторами.
            //Передача аргументов:
            //_prev.Position: Вектор, задающий начальную позицию для интерполяции(откуда начинаем движение).
            //curr.Position: Вектор, задающий конечную позицию для интерполяции(куда движемся).
            //delta: Коэффициент от 0 до 1, который мы вычислили ранее. Он определяет "пройденный путь" между начальной и конечной точками.
            //Вычисление внутри Lerp: Функция выполняет математическую операцию: Результат = НачальнаяПозиция + (КонечнаяПозиция - НачальнаяПозиция) * delta.
            //Если delta = 0, результат равен _prev.Position.
            //Если delta = 0.5, результат будет ровно посередине между двумя точками.
            //Если delta = 1, результат равен curr.Position.
            //Присвоение позиции: Полученный новый вектор позиции присваивается свойству transform.position игрового объекта.
            //Визуальный результат: В результате на экране объект плавно перемещается вдоль траектории, соединяющей все записанные точки, с той же скоростью, с которой он двигался при записи.
            transform.position = Vector3.Lerp(_prev.Position, curr.Position, delta);
		}
	}
}